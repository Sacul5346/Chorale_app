/// Verset du jour : le même pour toute la chorale un jour donné, et un
/// autre le lendemain (rotation sur la liste).
Verset versetDuJour(DateTime jour) {
  final numero =
      DateTime.utc(jour.year, jour.month, jour.day).millisecondsSinceEpoch ~/
      Duration.millisecondsPerDay;
  return versets[numero % versets.length];
}
